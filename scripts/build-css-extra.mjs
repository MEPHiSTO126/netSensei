import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const metaPath = path.join(root, "css-extra", "meta.json");
const outputPath = path.join(root, "prisma", "css-extra-phases.ts");

const meta = JSON.parse(fs.readFileSync(metaPath, "utf8"));
const phases = [];

for (const entry of meta.phases) {
  const sourcePath = path.join(root, "css-extra", entry.file);
  const source = fs.readFileSync(sourcePath, "utf8");
  const parts = source.split(/^@@@ /m).filter((part) => part.trim().length > 0);

  if (parts.length !== 6) {
    throw new Error(`${entry.file}: expected 6 stages, found ${parts.length}`);
  }

  const stages = parts.map((part, index) => {
    const newline = part.indexOf("\n");
    if (newline === -1) {
      throw new Error(`${entry.file}: stage ${index + 1} has no content`);
    }

    const header = part.slice(0, newline).trim();
    const separator = header.lastIndexOf("|");
    if (separator === -1) {
      throw new Error(`${entry.file}: stage ${index + 1} header needs a type`);
    }

    const title = header.slice(0, separator).trim();
    const type = header.slice(separator + 1).trim();
    const content = part.slice(newline + 1).trim();

    if (!title || !content) {
      throw new Error(`${entry.file}: stage ${index + 1} is incomplete`);
    }
    if (type !== "TEXT" && type !== "CHART") {
      throw new Error(`${entry.file}: unsupported stage type ${type}`);
    }

    return { title, type, content };
  });

  const charts = stages.filter((stage) => stage.type === "CHART");
  if (charts.length !== 1) {
    throw new Error(`${entry.file}: expected exactly 1 chart, found ${charts.length}`);
  }
  if (charts[0].content.includes(":")) {
    throw new Error(`${entry.file}: chart content must not contain a colon`);
  }

  if (!Array.isArray(entry.quiz?.questions)) {
    throw new Error(`${entry.file}: quiz questions are required`);
  }
  if (entry.quiz.questions.length < 5 || entry.quiz.questions.length > 6) {
    throw new Error(`${entry.file}: expected 5 or 6 quiz questions`);
  }

  for (const question of entry.quiz.questions) {
    if (!question.prompt || !question.expectedAnswer) {
      throw new Error(`${entry.file}: every question needs a prompt and expected answer`);
    }
    if (question.type === "SNIPPET" && !question.language) {
      throw new Error(`${entry.file}: snippet questions need a language`);
    }
  }

  phases.push({
    title: entry.title,
    order: entry.order,
    description: entry.description,
    stages,
    quiz: entry.quiz,
  });
}

phases.sort((a, b) => a.order - b.order);
for (let index = 0; index < phases.length; index += 1) {
  if (phases[index].order !== index + 6) {
    throw new Error("CSS extra phases must be numbered 6 through 9");
  }
}

const output = `// Generated by scripts/build-css-extra.mjs from css-extra/*.md and meta.json.
// Run npm run content:css after editing the source fragments.

export type CssExtraStage = {
  title: string;
  type: "TEXT" | "CHART";
  content: string;
};

export type CssExtraQuestion = {
  type: "SNIPPET" | "TEXT" | "AUDIO";
  language?: string;
  prompt: string;
  fullGoal?: string;
  expectedAnswer?: string;
  rubric?: string;
  points?: number;
};

export type CssExtraPhase = {
  title: string;
  order: number;
  description?: string;
  stages: CssExtraStage[];
  quiz?: {
    passThreshold?: number;
    questions: CssExtraQuestion[];
  };
};

export const cssExtraPhases: CssExtraPhase[] = ${JSON.stringify(phases, null, 2)};
`;

fs.writeFileSync(outputPath, output);
console.log(`Wrote ${phases.length} phases and ${phases.reduce((sum, phase) => sum + phase.stages.length, 0)} stages to ${path.relative(root, outputPath)}`);
